<?php
/*
 * Admin API for self-hosted deployments (PHP shared hosting, PHP 7.2+).
 *
 * The TV screens only ever read the static file data/config.json; this API is
 * used by admin.html to save it and to upload media. Auth is a password set on
 * first use (stored hashed in api/secret.php, never committed) that yields a
 * signed token.
 *
 *   GET  ?action=status                 -> { setup, maxUpload, writable }
 *   POST ?action=setup     {password}   -> { token }   (only while no password exists)
 *   POST ?action=login     {password}   -> { token }
 *   POST ?action=password  {old, new}   -> { token }   (auth)
 *   GET  ?action=whoami                 -> { ok }      (auth)
 *   GET  ?action=config                 -> data/config.json (fresh, uncached)
 *   POST ?action=save      {config, deletes[]}         (auth)
 *   POST ?action=upload    multipart: path, uploadId, index, total, chunk   (auth)
 */

header('Content-Type: application/json; charset=utf-8');
header('Cache-Control: no-store');
header('X-Content-Type-Options: nosniff');

define('ROOT', dirname(__DIR__));
define('CONFIG_FILE', ROOT . '/data/config.json');
define('MEDIA_DIR', ROOT . '/media');
define('BACKUP_DIR', ROOT . '/data/backups');
define('TMP_DIR', ROOT . '/data/uploads-tmp');
define('SECRET_FILE', __DIR__ . '/secret.php');
define('TOKEN_TTL', 30 * 24 * 3600);
define('KEEP_BACKUPS', 50);
define('MEDIA_RE', '/^media\/\d{8}-[a-z0-9]{6}\.(jpg|jpeg|png|gif|webp|mp4|webm)$/');

function out($data, $code = 200)
{
    http_response_code($code);
    echo json_encode($data, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    exit;
}

function fail($msg, $code = 400)
{
    out(array('ok' => false, 'error' => $msg), $code);
}

function body_json()
{
    $data = json_decode(file_get_contents('php://input'), true);
    return is_array($data) ? $data : array();
}

function require_post()
{
    if ($_SERVER['REQUEST_METHOD'] !== 'POST') fail('POST required', 405);
}

/* ---------- secret & tokens ---------- */
function secret()
{
    if (!is_file(SECRET_FILE)) return null;
    $s = include SECRET_FILE;
    return is_array($s) ? $s : null;
}

function write_secret($password)
{
    $s = array('hash' => password_hash($password, PASSWORD_DEFAULT), 'key' => bin2hex(random_bytes(32)));
    $php = "<?php\n// Generated by api/index.php - admin password hash and token key. Do not share.\nreturn " . var_export($s, true) . ";\n";
    if (file_put_contents(SECRET_FILE, $php, LOCK_EX) === false) fail('cannot write api/secret.php (check folder permissions)', 500);
    @chmod(SECRET_FILE, 0600);
    if (function_exists('opcache_invalidate')) @opcache_invalidate(SECRET_FILE, true);
    return $s;
}

function make_token($s)
{
    $exp = (string)(time() + TOKEN_TTL);
    return $exp . '.' . hash_hmac('sha256', $exp, $s['key']);
}

function require_auth()
{
    $s = secret();
    if (!$s) fail('not set up', 403);
    $t = isset($_SERVER['HTTP_X_AUTH']) ? $_SERVER['HTTP_X_AUTH'] : (isset($_POST['token']) ? $_POST['token'] : '');
    $parts = explode('.', (string)$t, 2);
    if (count($parts) !== 2 || (int)$parts[0] < time() ||
        !hash_equals(hash_hmac('sha256', $parts[0], $s['key']), $parts[1])) {
        fail('unauthorized', 401);
    }
}

function check_password($password)
{
    $s = secret();
    if (!$s || !password_verify((string)$password, $s['hash'])) {
        sleep(1); // slow down guessing
        fail('รหัสผ่านไม่ถูกต้อง', 401);
    }
}

/* ---------- helpers ---------- */
function ini_bytes($v)
{
    $v = trim((string)$v);
    if ($v === '') return 0;
    $n = (float)$v;
    switch (strtolower(substr($v, -1))) {
        case 'g': $n *= 1024;
        case 'm': $n *= 1024;
        case 'k': $n *= 1024;
    }
    return (int)$n;
}

/* Folders that must never be served (backups contain customer bookings). */
function private_dir($dir)
{
    if (!is_dir($dir) && !@mkdir($dir, 0755, true)) fail('cannot create ' . basename($dir), 500);
    $ht = $dir . '/.htaccess';
    if (!is_file($ht)) {
        file_put_contents($ht, "<IfModule mod_authz_core.c>\n  Require all denied\n</IfModule>\n<IfModule !mod_authz_core.c>\n  Deny from all\n</IfModule>\n");
    }
}

function write_atomic($file, $data)
{
    $tmp = $file . '.tmp-' . bin2hex(random_bytes(4));
    if (file_put_contents($tmp, $data, LOCK_EX) === false) fail('cannot write ' . basename($file), 500);
    if (!@rename($tmp, $file)) {
        // Windows hosts cannot rename over an existing file
        @unlink($file);
        if (!@rename($tmp, $file)) { @unlink($tmp); fail('cannot replace ' . basename($file), 500); }
    }
}

/* Backups are stored as .php files that exit immediately: nginx (e.g. Plesk) serves static files
   without reading .htaccess, so a plain .json backup with customer bookings could be downloaded.
   To restore one, delete its first line and save it as data/config.json. */
function backup_config()
{
    if (!is_file(CONFIG_FILE)) return;
    private_dir(BACKUP_DIR);
    file_put_contents(BACKUP_DIR . '/config-' . date('Ymd-His') . '.json.php',
        "<?php http_response_code(404); exit; ?>
" . file_get_contents(CONFIG_FILE));
    $all = glob(BACKUP_DIR . '/config-*.json.php') ?: array();
    sort($all);
    while (count($all) > KEEP_BACKUPS) @unlink(array_shift($all));
}

/* ---------- actions ---------- */
$action = isset($_GET['action']) ? $_GET['action'] : '';

switch ($action) {
    case 'status':
        out(array(
            'ok' => true,
            'setup' => secret() !== null,
            'maxUpload' => min(ini_bytes(ini_get('upload_max_filesize')), ini_bytes(ini_get('post_max_size'))),
            'writable' => is_writable(ROOT . '/data') && is_writable(MEDIA_DIR) && is_writable(__DIR__),
            'php' => PHP_VERSION
        ));

    case 'setup':
        require_post();
        if (secret()) fail('ตั้งรหัสผ่านไปแล้ว', 409);
        $b = body_json();
        $pw = isset($b['password']) ? (string)$b['password'] : '';
        if (strlen($pw) < 8) fail('รหัสผ่านต้องยาวอย่างน้อย 8 ตัวอักษร');
        out(array('ok' => true, 'token' => make_token(write_secret($pw))));

    case 'login':
        require_post();
        $b = body_json();
        check_password(isset($b['password']) ? $b['password'] : '');
        out(array('ok' => true, 'token' => make_token(secret())));

    case 'password':
        require_post();
        require_auth();
        $b = body_json();
        check_password(isset($b['old']) ? $b['old'] : '');
        $new = isset($b['new']) ? (string)$b['new'] : '';
        if (strlen($new) < 8) fail('รหัสผ่านใหม่ต้องยาวอย่างน้อย 8 ตัวอักษร');
        // new key = every other logged-in device is signed out
        out(array('ok' => true, 'token' => make_token(write_secret($new))));

    case 'whoami':
        require_auth();
        out(array('ok' => true));

    case 'config':
        if (!is_file(CONFIG_FILE)) fail('config.json not found', 404);
        readfile(CONFIG_FILE);
        exit;

    case 'save':
        require_post();
        require_auth();
        $b = body_json();
        $cfg = isset($b['config']) ? $b['config'] : null;
        if (!is_array($cfg) || !isset($cfg['rooms']) || !isset($cfg['playlists'])) fail('invalid config');
        backup_config();
        write_atomic(CONFIG_FILE, json_encode($cfg, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT) . "\n");
        $deleted = 0;
        if (isset($b['deletes']) && is_array($b['deletes'])) {
            foreach ($b['deletes'] as $p) {
                if (is_string($p) && preg_match(MEDIA_RE, $p) && is_file(ROOT . '/' . $p) && @unlink(ROOT . '/' . $p)) $deleted++;
            }
        }
        out(array('ok' => true, 'deleted' => $deleted));

    case 'upload':
        require_post();
        require_auth();
        $path = isset($_POST['path']) ? (string)$_POST['path'] : '';
        $id = isset($_POST['uploadId']) ? (string)$_POST['uploadId'] : '';
        $index = isset($_POST['index']) ? (int)$_POST['index'] : -1;
        $total = isset($_POST['total']) ? (int)$_POST['total'] : 0;
        if (!preg_match(MEDIA_RE, $path)) fail('ชื่อไฟล์ไม่ถูกต้อง');
        if (!preg_match('/^[a-z0-9]{6,40}$/', $id) || $index < 0 || $total < 1 || $index >= $total) fail('bad chunk');
        if (!isset($_FILES['chunk']) || $_FILES['chunk']['error'] !== UPLOAD_ERR_OK) {
            $err = isset($_FILES['chunk']) ? $_FILES['chunk']['error'] : -1;
            fail($err === UPLOAD_ERR_INI_SIZE || $err === UPLOAD_ERR_FORM_SIZE ? 'ไฟล์ส่วนนี้ใหญ่เกินที่ Host อนุญาต' : 'อัปโหลดไม่สำเร็จ (code ' . $err . ')');
        }
        private_dir(TMP_DIR);
        $part = TMP_DIR . '/' . $id . '.part';
        $in = fopen($_FILES['chunk']['tmp_name'], 'rb');
        $outF = fopen($part, $index === 0 ? 'wb' : 'ab');
        if (!$in || !$outF) fail('cannot write upload', 500);
        stream_copy_to_stream($in, $outF);
        fclose($in);
        fclose($outF);
        if ($index < $total - 1) out(array('ok' => true, 'received' => $index + 1));

        // last chunk: check the real file type matches the extension, then publish it
        $ext = strtolower(pathinfo($path, PATHINFO_EXTENSION));
        $mime = function_exists('mime_content_type') ? (string)mime_content_type($part) : '';
        $isVideo = in_array($ext, array('mp4', 'webm'), true);
        if ($mime !== '' && strpos($mime, $isVideo ? 'video/' : 'image/') !== 0 && $mime !== 'application/octet-stream') {
            @unlink($part);
            fail('ชนิดไฟล์ไม่ตรงกับนามสกุล (' . $mime . ')');
        }
        if (!is_dir(MEDIA_DIR)) @mkdir(MEDIA_DIR, 0755, true);
        if (!@rename($part, ROOT . '/' . $path)) { @unlink($part); fail('cannot save media', 500); }
        @chmod(ROOT . '/' . $path, 0644);
        // tidy abandoned uploads older than a day
        foreach ((glob(TMP_DIR . '/*.part') ?: array()) as $old) if (filemtime($old) < time() - 86400) @unlink($old);
        out(array('ok' => true, 'path' => $path, 'size' => filesize(ROOT . '/' . $path)));

    default:
        fail('unknown action', 404);
}
